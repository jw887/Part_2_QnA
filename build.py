#!/usr/bin/env python3
"""
Bundle data/chNNN.json chapter files into questions.js for the app.

Usage:  python3 build.py

- Each chapter file holds one daily topic (see data/ch001.json for the format).
- Answer options are shuffled with a fixed seed so the correct answer is not
  always in the same position, but the order stays the same every build.
- Options containing "of the above" stay in last place.
- Question IDs are stable ("c001-q01"), so progress saved in the browser
  survives rebuilds as long as you only ADD questions at the end of a chapter.
"""
import glob, json, random, os

HERE = os.path.dirname(os.path.abspath(__file__))
chapters = []
for path in sorted(glob.glob(os.path.join(HERE, "data", "ch*.json"))):
    with open(path, encoding="utf-8") as f:
        ch = json.load(f)
    qs = []
    for i, q in enumerate(ch["questions"]):
        qid = f"c{ch['no']:03d}-q{i+1:02d}"
        opts = list(enumerate(q["options"]))
        fixed = [o for o in opts if "of the above" in o[1].lower()]
        movable = [o for o in opts if o not in fixed]
        random.Random(qid).shuffle(movable)
        opts = movable + fixed
        new_answer = [k for k, (orig, _) in enumerate(opts) if orig == q["answer"]][0]
        qs.append({
            "id": qid,
            "stem": q["stem"],
            "options": [t for _, t in opts],
            "answer": new_answer,
            "explanation": q["explanation"],
            "ref": q.get("ref", ""),
        })
    chapters.append({
        "no": ch["no"], "title": ch["title"], "section": ch["section"],
        "delivered": ch.get("delivered", ""), "questions": qs,
    })

out = "// Generated by build.py – do not edit by hand. Edit data/chNNN.json instead.\n"
out += "window.QBANK = " + json.dumps({"chapters": chapters}, ensure_ascii=False, indent=1) + ";\n"
with open(os.path.join(HERE, "questions.js"), "w", encoding="utf-8") as f:
    f.write(out)

n = sum(len(c["questions"]) for c in chapters)
dist = [0] * 5
for c in chapters:
    for q in c["questions"]:
        dist[q["answer"]] += 1
print(f"Built questions.js: {len(chapters)} chapters, {n} questions")
print("Answer position spread A–E:", dist)
